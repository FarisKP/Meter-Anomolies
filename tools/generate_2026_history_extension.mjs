import fs from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const sourcePath = path.join(root, "meter_usage_5cust_3years (1).csv");
const csvOutputPath = path.join(root, "meter_usage_5cust_2026_jan_sep.csv");
const sqlOutputPath = path.join(root, "db", "007_import_history_through_2026_09.sql");

const START = Date.UTC(2026, 0, 1, 0, 0, 0);
const END = Date.UTC(2026, 8, 30, 20, 0, 0);
const FOUR_HOURS = 4 * 60 * 60 * 1000;
const EXPECTED_ROWS = 5 * 273 * 6;
const header = [
  "cust-id",
  "meter-num",
  "meter-status",
  "current-meter-read",
  "current-meter-read-timestamp",
  "previous-meter-read",
  "usage-index",
  "budget indicator",
];

function parseCsv(text) {
  const [headerLine, ...lines] = text.trim().split(/\r?\n/);
  const columns = headerLine.split(",");
  return lines.map((line) => Object.fromEntries(columns.map((column, index) => [column, line.split(",")[index]])));
}

function timestampForCsv(epochMillis) {
  return new Date(epochMillis).toISOString().slice(0, 19).replace("T", " ");
}

function cents(value) {
  return Math.round(Number(value) * 100);
}

function money(valueInCents) {
  return (valueInCents / 100).toFixed(2);
}

function usageCents(dayIndex, slotIndex, customerOrdinal) {
  // Normal, deterministic usage (about 1.32 to 3.19 per four-hour interval).
  // Integer cents keep the generated CSV and SQL import exactly aligned.
  return 125 + customerOrdinal * 7 + ((dayIndex * 17 + slotIndex * 11 + customerOrdinal * 13) % 160);
}

function sqlLiteral(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

function buildSql(seeds) {
  const values = seeds
    .map((seed) => `        (${sqlLiteral(seed.customerId)}, ${sqlLiteral(seed.meterId)}, ${sqlLiteral(seed.budgetIndicator)}, ${seed.initialCents}, ${seed.ordinal})`)
    .join(",\n");

  return `-- Historical continuation for 2026-01-01 00:00 UTC through 2026-09-30 20:00 UTC.
-- Generated by tools/generate_2026_history_extension.mjs from the supplied
-- historical CSV's final reading for each customer. It creates 8,190 normal
-- four-hour readings and does not create current-feed rows, spike results, or
-- meter_reads_temp queue entries.
--
-- Safe to re-run: meter_reads is upserted by (meter_id, read_at).

BEGIN;

INSERT INTO ingest_batches (batch_id, source_name, imported_at, record_count)
VALUES (
    'history-csv-initial',
    'meter_usage_5cust_3years (1).csv + meter_usage_5cust_2026_jan_sep.csv',
    CURRENT_TIMESTAMP,
    0
)
ON CONFLICT (batch_id) DO UPDATE
SET source_name = EXCLUDED.source_name,
    imported_at = EXCLUDED.imported_at;

WITH seed (customer_id, meter_id, budget_indicator, initial_current_cents, customer_ordinal) AS (
    VALUES
${values}
),
slots AS (
    SELECT
        reading_at AS read_at,
        (reading_at::date - DATE '2026-01-01')::integer AS day_index,
        (EXTRACT(HOUR FROM reading_at)::integer / 4) AS slot_index
    FROM generate_series(
        TIMESTAMP '2026-01-01 00:00:00',
        TIMESTAMP '2026-09-30 20:00:00',
        INTERVAL '4 hours'
    ) AS generated_slot(reading_at)
),
generated AS (
    SELECT
        seed.customer_id,
        seed.meter_id,
        seed.budget_indicator,
        seed.initial_current_cents,
        slots.read_at,
        125 + seed.customer_ordinal * 7
            + ((slots.day_index * 17 + slots.slot_index * 11 + seed.customer_ordinal * 13) % 160)
            AS usage_cents
    FROM seed
    CROSS JOIN slots
),
rolled AS (
    SELECT
        customer_id,
        meter_id,
        budget_indicator,
        read_at,
        usage_cents,
        initial_current_cents
            + COALESCE(
                SUM(usage_cents) OVER (
                    PARTITION BY meter_id
                    ORDER BY read_at
                    ROWS BETWEEN UNBOUNDED PRECEDING AND 1 PRECEDING
                ),
                0
            ) AS previous_cents,
        initial_current_cents
            + SUM(usage_cents) OVER (
                PARTITION BY meter_id
                ORDER BY read_at
                ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW
            ) AS current_cents
    FROM generated
)
INSERT INTO meter_reads (
    read_id,
    meter_id,
    read_at,
    meter_status,
    current_read,
    previous_read,
    usage_index,
    budget_indicator,
    slot_hour,
    batch_id,
    read_type
)
SELECT
    md5(customer_id || chr(31) || meter_id || chr(31) || to_char(read_at, 'YYYY-MM-DD HH24:MI:SS')),
    meter_id,
    read_at,
    'ACTIVE',
    current_cents / 100.0,
    previous_cents / 100.0,
    usage_cents / 100.0,
    budget_indicator,
    EXTRACT(HOUR FROM read_at)::smallint,
    'history-csv-initial',
    'actual'
FROM rolled
ON CONFLICT (meter_id, read_at) DO UPDATE
SET meter_status = EXCLUDED.meter_status,
    current_read = EXCLUDED.current_read,
    previous_read = EXCLUDED.previous_read,
    usage_index = EXCLUDED.usage_index,
    budget_indicator = EXCLUDED.budget_indicator,
    slot_hour = EXCLUDED.slot_hour,
    batch_id = EXCLUDED.batch_id,
    read_type = EXCLUDED.read_type;

UPDATE ingest_batches
SET source_name = 'meter_usage_5cust_3years (1).csv + meter_usage_5cust_2026_jan_sep.csv',
    imported_at = CURRENT_TIMESTAMP,
    record_count = (
        SELECT COUNT(*)
        FROM meter_reads
        WHERE batch_id = 'history-csv-initial'
    )
WHERE batch_id = 'history-csv-initial';

COMMIT;
`;
}

const rows = parseCsv(await fs.readFile(sourcePath, "utf8"));
const finalTimestamp = "2025-12-31 20:00:00";
const lastReadByCustomer = new Map();
for (const row of rows) {
  if (row["current-meter-read-timestamp"] === finalTimestamp) {
    lastReadByCustomer.set(row["cust-id"], row);
  }
}

if (lastReadByCustomer.size !== 5) {
  throw new Error(`Expected final readings for five customers at ${finalTimestamp}; found ${lastReadByCustomer.size}.`);
}

const seeds = [...lastReadByCustomer.values()]
  .sort((left, right) => left["cust-id"].localeCompare(right["cust-id"]))
  .map((row, index) => ({
    customerId: row["cust-id"],
    meterId: row["meter-num"],
    meterStatus: row["meter-status"],
    budgetIndicator: row["budget indicator"],
    initialCents: cents(row["current-meter-read"]),
    ordinal: index + 1,
  }));

const csvRows = [header.join(",")];
for (const seed of seeds) {
  let previousCents = seed.initialCents;
  for (let epochMillis = START, rowIndex = 0; epochMillis <= END; epochMillis += FOUR_HOURS, rowIndex += 1) {
    const dayIndex = Math.floor(rowIndex / 6);
    const slotIndex = rowIndex % 6;
    const intervalUsageCents = usageCents(dayIndex, slotIndex, seed.ordinal);
    const currentCents = previousCents + intervalUsageCents;
    csvRows.push([
      seed.customerId,
      seed.meterId,
      seed.meterStatus,
      money(currentCents),
      timestampForCsv(epochMillis),
      money(previousCents),
      money(intervalUsageCents),
      seed.budgetIndicator,
    ].join(","));
    previousCents = currentCents;
  }
}

if (csvRows.length - 1 !== EXPECTED_ROWS) {
  throw new Error(`Expected ${EXPECTED_ROWS} generated rows; received ${csvRows.length - 1}.`);
}

await fs.writeFile(csvOutputPath, `${csvRows.join("\n")}\n`, "utf8");
await fs.writeFile(sqlOutputPath, buildSql(seeds), "utf8");

console.log(`Created ${path.basename(csvOutputPath)} with ${EXPECTED_ROWS} readings.`);
console.log(`Created ${path.relative(root, sqlOutputPath)} for an idempotent Supabase import.`);
console.log(`Range: ${timestampForCsv(START)} through ${timestampForCsv(END)} UTC.`);
